def get_pack(language_code: str) -> Dict:
    """Return the language pack for the given ISO 639-1 code.

    Raises ValueError if the language is not supported.
    """
    code = (language_code or "").lower()
    if code not in LANGUAGE_PACKS:
        raise ValueError(
            f"Unsupported language code: {language_code!r}. "
            f"Supported: {', '.join(SUPPORTED_LANGUAGES)}"
        )
    return LANGUAGE_PACKS[code]


def is_supported(language_code: str) -> bool:
    """Return True if the ISO 639-1 code is in the supported list."""
    return (language_code or "").lower() in LANGUAGE_PACKS


if __name__ == "__main__":
    # Sanity check: verify all packs have the same top-level keys
    import sys

    reference_keys = set(LANGUAGE_PACKS["en"].keys())
    reference_dim_keys = set(LANGUAGE_PACKS["en"]["dimensions"].keys())

    failures = []
    for code, pack in LANGUAGE_PACKS.items():
        missing = reference_keys - set(pack.keys())
        if missing:
            failures.append(f"{code} missing top-level keys: {missing}")
        if "dimensions" in pack:
            missing_dims = reference_dim_keys - set(pack["dimensions"].keys())
            if missing_dims:
                failures.append(f"{code} missing dimension keys: {missing_dims}")

    if failures:
        for f in failures:
            print(f"FAIL: {f}", file=sys.stderr)
        sys.exit(1)
    print(f"OK: all {len(LANGUAGE_PACKS)} packs match canonical English key set")
